// Scans public/images and writes src/content/images.generated.ts so every
// image slot on the site knows whether a real image has been added.
// Runs automatically before `npm run dev` and `npm run build`.
import { readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, parse } from "node:path";

const dir = join(process.cwd(), "public", "images");
if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
const exts = new Set([".webp", ".avif", ".jpg", ".jpeg", ".png", ".gif"]);
const map = {};
for (const f of readdirSync(dir).sort()) {
  const p = parse(f);
  if (exts.has(p.ext.toLowerCase()) && !map[p.name]) map[p.name] = `/images/${f}`;
}
const out = `// Generated by scripts/scan-images.mjs. Do not edit by hand.\nexport const images: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
writeFileSync(join(process.cwd(), "src", "content", "images.generated.ts"), out);
console.log(`images: ${Object.keys(map).length} found in public/images`);
